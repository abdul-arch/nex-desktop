// Adaptateur desktop : appels IPC Tauri. Aucun acces fichier/shell/URL direct
// depuis le frontend ; tout passe par des commandes Rust validees.
import { convertFileSrc, invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import { getCurrentWindow } from "@tauri-apps/api/window";
import type { Platform, Settings, SettingKey } from "./contracts";

export function createDesktopPlatform(): Platform {
  const win = getCurrentWindow();
  return {
    capabilities: { kind: "desktop", windowControls: true, localClient: true, persistentStorage: true },
    appInfo: () => invoke("app_info"),
    getSettings: () => invoke("settings_get"),
    setSetting: <K extends SettingKey>(key: K, value: Settings[K]) =>
      invoke<Settings>("settings_set", { key, value }),
    listFavorites: () => invoke("favorites_list"),
    addFavorite: (riotId, platform) => invoke("favorites_add", { riotId, platform }),
    removeFavorite: (id) => invoke("favorites_remove", { id }),
    listRecentSearches: () => invoke("recent_searches_list"),
    pushRecentSearch: (riotId, platform) => invoke("recent_search_push", { riotId, platform }),
    clearRecentSearches: () => invoke("recent_searches_clear"),
    staticDataVersion: () => invoke("static_data_version"),
    staticCatalog: () => invoke("static_catalog"),
    openExternal: (url) => invoke("open_external", { url }),
    backendHealth: () => invoke("backend_health"),
    playerProfile: (riotId, platform, refresh = false) => invoke("player_profile", { riotId, platform, refresh }),
    playerMatches: (args) => invoke("player_matches", { ...args }),
    matchGet: (platform, matchId) => invoke("match_get", { platform, matchId }),
    matchTimeline: (platform, matchId) => invoke("match_timeline", { platform, matchId }),
    statsMeta: () => invoke("stats_meta"),
    statsTierList: (params) => invoke("stats_tierlist", { params }),
    statsBaselines: (params) => invoke("stats_baselines", { params }),
    statsBuild: (championId, params) => invoke("stats_build", { championId, params }),
    statsMatchups: (championId, params) => invoke("stats_matchups", { championId, params }),
    championInfo: (key) => invoke("champion_info", { key }),
    windowLabel: win.label,
    clientState: () => invoke("client_state"),
    champSelect: () => invoke("client_champ_select"),
    liveSnapshot: () => invoke("live_snapshot"),
    importRunes: (input) => invoke("lcu_import_runes", { input }),
    importItems: (input) => invoke("lcu_import_items", { input }),
    overlayOpen: (config) => invoke("overlay_open", { config }),
    overlayClose: () => invoke("overlay_close"),
    overlaySetMode: (config) => invoke("overlay_set_mode", { config }),
    overlayMode: () => invoke("overlay_mode"),
    overlayLayoutGet: () => invoke("overlay_layout_get"),
    overlayLayoutSet: (widget) => invoke("overlay_layout_set", { widget }),
    overlayLayoutReset: () => invoke("overlay_layout_reset"),
    on: (event, cb) => listen(event, (e) => cb(e.payload as never)),
    captureStatus: () => invoke("capture_status"),
    captureSources: () => invoke("capture_sources"),
    captureStart: (source, keepAll) => invoke("capture_start", { source, keepAll }),
    captureStop: () => invoke("capture_stop"),
    captureSaveClip: (seconds, title) => invoke("capture_save_clip", { seconds, title: title ?? null }),
    recordingsList: () => invoke("recordings_list"),
    recordingsStorage: () => invoke("recordings_storage"),
    recordingSetFavorite: (id, favorite) => invoke("recording_set_favorite", { id, favorite }),
    recordingDelete: (id) => invoke("recording_delete", { id }),
    recordingReveal: (id) => invoke("recording_reveal", { id }),
    assetUrl: (path) => convertFileSrc(path),
    skinCatalog: () => invoke("skin_catalog"),
    skinInventory: () => invoke("skin_inventory"),
    leaderboard: (platform, queue, tier, page) => invoke("leaderboard_get", { platform, queue, tier, page }),
    liveGame: (platform, puuid) => invoke("live_game_get", { platform, puuid }),
    rankHistory: (platform, puuid, queue = "") => invoke("rank_history", { platform, puuid, queue }),
    proTeams: () => invoke("pro_teams"),
    spectate: (riotId) => invoke("lcu_spectate", { riotId }),
    observableFriends: () => invoke("lcu_observable_friends"),
    localMayhemMatches: (riotId, puuid, count) => invoke("lcu_match_history", { riotId, puuid, count: count ?? null }),
    mayhemCatalog: () => invoke("mayhem_catalog"),
    mayhemRules: () => invoke("mayhem_rules"),
    mayhemSaveRule: (rule) => invoke("mayhem_save_rule", { rule }),
    mayhemDeleteRule: (key) => invoke("mayhem_delete_rule", { key }),
    mayhemRate: (req) => invoke("mayhem_rate", { req }),
    mayhemManual: (offered) => invoke("mayhem_manual", { offered }),
    mayhemDemo: (on) => invoke("mayhem_demo", { on }),
    mayhemClear: () => invoke("mayhem_clear"),
    mayhemConfirm: (key, chosen) => invoke("mayhem_confirm", { key, chosen }),
    mayhemConfirmed: () => invoke("mayhem_confirmed"),
    mayhemReadNow: () => invoke("mayhem_read_now"),
    mayhemState: () => invoke("mayhem_state"),
    mayhemDataset: () => invoke("mayhem_dataset"),
    window: {
      minimize: () => win.minimize(),
      toggleMaximize: () => win.toggleMaximize(),
      close: () => win.close(),
      isMaximized: () => win.isMaximized(),
      onResized: (cb) => win.onResized(() => cb()),
    },
  };
}
